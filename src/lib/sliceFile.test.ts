import { describe, expect, it } from 'vitest'
import { MAX_KEEP_BYTES, mb, packFile, tooBigNote, unpackFile } from './sliceFile'

const GCODE = `; generated by PrusaSlicer
${'G1 X10.5 Y20.25 E0.04512 F1800\n'.repeat(4000)}
; filament used [g] = 86.5
`

function bytes(s: string): Uint8Array {
  return new TextEncoder().encode(s)
}

describe('keeping the file', () => {
  it('gives back exactly what went in', async () => {
    const original = bytes(GCODE)
    const kept = await packFile(original)
    expect(kept).not.toBeNull()
    const back = await unpackFile(kept!.content)
    expect(new TextDecoder().decode(back)).toBe(GCODE)
  })

  it('stores a fraction of the original, because G-code is text', async () => {
    const original = bytes(GCODE)
    const kept = await packFile(original)
    expect(kept!.byteSize).toBe(original.byteLength)
    // Base64 of gzip still well under half the raw file; if this ever
    // stops being true the cap is the wrong shape.
    expect(kept!.storedSize).toBeLessThan(original.byteLength / 2)
  })

  it('survives a file big enough to break fromCharCode(...bytes)', async () => {
    // 300 KB of random-ish binary: over the 32 KB chunk, and incompressible
    // enough that the base64 pass is doing real work.
    const raw = new Uint8Array(300 * 1024)
    for (let i = 0; i < raw.length; i++) raw[i] = (i * 2654435761) % 256
    const kept = await packFile(raw)
    const back = await unpackFile(kept!.content)
    expect(back.byteLength).toBe(raw.byteLength)
    expect(back[12345]).toBe(raw[12345])
  })

  it('refuses a file over the cap rather than keeping half of it', async () => {
    const huge = new Uint8Array(MAX_KEEP_BYTES + 1)
    expect(await packFile(huge)).toBeNull()
  })

  it('says why, in a sentence with sizes in it', () => {
    const note = tooBigNote(MAX_KEEP_BYTES + 1)
    expect(note).toMatch(/40 MB/)
    expect(note).toMatch(/only what it said/)
  })

  it('reads sizes the way a person would say them', () => {
    expect(mb(512)).toBe('512 B')
    expect(mb(2048)).toBe('2 KB')
    expect(mb(5 * 1024 * 1024)).toBe('5 MB')
  })
})
