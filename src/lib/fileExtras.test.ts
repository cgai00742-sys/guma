import { describe, expect, it } from 'vitest'
import { readFileSync, existsSync } from 'node:fs'
import { decodeQoi, fileExtras, slicedDate } from './fileExtras'

const fileOf = (name: string, data: Uint8Array | string) => ({
  name,
  arrayBuffer: async () => (typeof data === 'string' ? new TextEncoder().encode(data) : data).slice().buffer as ArrayBuffer,
  text: async () => (typeof data === 'string' ? data : new TextDecoder().decode(data)),
})

describe('what a sliced file shows about itself (CG, 22 Oct)', () => {
  it('reads when PrusaSlicer made the file', () => {
    expect(slicedDate('2026-09-15 at 18:08:06 UTC')).toBe('2026-09-15T18:08:06Z')
    expect(slicedDate('2026-09-15')).toBe('2026-09-15T00:00:00Z')
    expect(slicedDate('soon')).toBeNull()
  })
  it('takes the picture and the date out of plain G-code', async () => {
    const png = btoa(String.fromCharCode(0x89, 0x50, 0x4e, 0x47, 1, 2, 3))
    const src = `; generated by PrusaSlicer 2.8.1 on 2026-10-13 at 09:30:00 UTC\n;\n; thumbnail begin 16x16 10\n; AAAA\n; thumbnail end\n; thumbnail begin 313x173 ${png.length}\n; ${png}\n; thumbnail end\nG1 X1\n`
    const x = await fileExtras(fileOf('a.gcode', src))
    expect(x.slicedAt).toBe('2026-10-13T09:30:00Z')
    expect(x.thumbnail).toBe(`data:image/png;base64,${png}`)
  })
  it('says nothing rather than fail on a file with neither', async () => {
    expect(await fileExtras(fileOf('a.gcode', 'G1 X1\n'))).toEqual({ thumbnail: null, slicedAt: null })
  })
  it('decodes QOI, the format Prusa screens use', () => {
    // 1x2: one red pixel (RGB op), then a run of 1.
    const q = new Uint8Array([0x71, 0x6f, 0x69, 0x66, 0, 0, 0, 1, 0, 0, 0, 2, 4, 0, 0xfe, 255, 0, 0, 0xc0, 0, 0, 0, 0, 0, 0, 0, 1])
    const img = decodeQoi(q)!
    expect([img.w, img.h]).toEqual([1, 2])
    expect([...img.rgba]).toEqual([255, 0, 0, 255, 255, 0, 0, 255])
  })
  it('reads CG’s Maui .bgcode: the PNG preview and "Produced on"', async () => {
    const path = '/tmp/claude-0/bg/maui.bgcode'
    if (!existsSync(path)) return
    const x = await fileExtras(fileOf('maui.bgcode', new Uint8Array(readFileSync(path))))
    expect(x.slicedAt).toBe('2026-09-15T18:08:06Z')
    expect(x.thumbnail?.startsWith('data:image/png;base64,iVBOR')).toBe(true)
  })
})
